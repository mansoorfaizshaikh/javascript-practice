// Student Grade System

let marks = 72;

// Marks ke hisab se grade decide karo
if (marks >= 90) {

    console.log("Grade A");

} else if (marks >= 75) {

    console.log("Grade B");

} else if (marks >= 60) {

    console.log("Grade C");

} else if (marks >= 40) {

    console.log("Pass");

} else {

    console.log("Fail");

}